import { readFile } from "node:fs/promises";
import {
  BIQUOTE_BASE_URL,
  BIQUOTE_MAPPING_FILE,
  PRICE_CANDLE_LIMIT,
} from "./config";

/**
 * Intervals that Biquote exposes directly. The signal timeframes `5h` and `1w`
 * are intentionally not requested here: they can be aggregated later from the
 * stored `1h` and `1d` candles.
 */
export const PRICE_INTERVALS = [
  "5m",
  "15m",
  "30m",
  "1h",
  "4h",
  "1d",
] as const;

export type PriceInterval = (typeof PRICE_INTERVALS)[number];

export interface PriceCandle {
  symbol: string;
  timeframe: PriceInterval;
  openTime: number;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number | null;
  tickVolume: number | null;
}

export interface MappedSymbol {
  original: string;
  symbol: string;
}

interface BiquoteBar {
  openTime: string;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
  tickVolume: number;
  isOpen: boolean;
}

interface BiquoteOhlcResponse {
  symbol: string;
  interval: string;
  bars: BiquoteBar[];
}

// Minimal CSV parser supporting quoted fields and escaped quotes.
function parseCsvLine(line: string): string[] {
  const result: string[] = [];
  let value = "";
  let quoted = false;

  for (let i = 0; i < line.length; i++) {
    const char = line[i];

    if (char === '"') {
      if (quoted && line[i + 1] === '"') {
        value += '"';
        i++;
      } else {
        quoted = !quoted;
      }
    } else if (char === "," && !quoted) {
      result.push(value);
      value = "";
    } else {
      value += char;
    }
  }

  result.push(value);
  return result;
}

function normalizeHeader(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

function findColumn(headers: string[], candidates: string[]): number {
  const normalized = headers.map(normalizeHeader);

  for (const candidate of candidates) {
    const index = normalized.indexOf(normalizeHeader(candidate));
    if (index !== -1) return index;
  }

  return -1;
}

let mappedSymbolsCache: MappedSymbol[] | null = null;

/**
 * Reads every active original -> canonical mapping generated by
 * `src/map-biquote.ts`. Multiple signal-side aliases may share one canonical
 * instrument; use loadUniqueMappedSymbols() when building market-data requests.
 */
export async function loadMappedSymbols(): Promise<MappedSymbol[]> {
  if (mappedSymbolsCache) return mappedSymbolsCache;

  const content = await readFile(BIQUOTE_MAPPING_FILE, "utf8");
  const lines = content.trim().split(/\r?\n/);

  if (lines.length < 2) {
    throw new Error(`No mapping rows found in ${BIQUOTE_MAPPING_FILE}`);
  }

  const headers = parseCsvLine(lines[0]!);
  const inputIndex = findColumn(headers, ["original", "input"]);
  const symbolIndex = findColumn(headers, ["matched", "biquoteSymbol"]);
  const statusIndex = findColumn(headers, ["status"]);

  if (symbolIndex === -1 || statusIndex === -1) {
    throw new Error(
      `Invalid mapping CSV headers: ${headers.join(", ")}`,
    );
  }

  // Keep every active original -> canonical alias. A canonical symbol may
  // legitimately be referenced by more than one signal-side name.
  const byOriginal = new Map<string, MappedSymbol>();

  for (const line of lines.slice(1)) {
    if (!line.trim()) continue;

    const columns = parseCsvLine(line);
    const symbol = columns[symbolIndex]?.trim();
    const status = columns[statusIndex]?.trim().toUpperCase();
    const original =
      inputIndex >= 0 ? columns[inputIndex]?.trim() || symbol : symbol;

    if (!symbol || !original || status !== "ACTIVE") continue;

    const key = original.toUpperCase();
    const existing = byOriginal.get(key);

    if (existing && existing.symbol.toUpperCase() !== symbol.toUpperCase()) {
      throw new Error(
        `Conflicting active mappings for ${original}: ${existing.symbol} / ${symbol}`,
      );
    }

    if (!existing) byOriginal.set(key, { original, symbol });
  }

  mappedSymbolsCache = [...byOriginal.values()];
  return mappedSymbolsCache;
}

/**
 * Returns one request mapping per canonical instrument. Use this only for
 * market-data collection; alias resolution must use loadMappedSymbols().
 */
export async function loadUniqueMappedSymbols(): Promise<MappedSymbol[]> {
  const mappings = await loadMappedSymbols();
  const byCanonical = new Map<string, MappedSymbol>();

  for (const mapping of mappings) {
    const key = mapping.symbol.toUpperCase();
    if (!byCanonical.has(key)) byCanonical.set(key, mapping);
  }

  return [...byCanonical.values()];
}

function isValidBar(bar: BiquoteBar): boolean {
  const values = [bar.open, bar.high, bar.low, bar.close];

  if (!values.every(Number.isFinite)) return false;
  if (values.some((value) => value <= 0)) return false;
  if (!bar.openTime || !Number.isFinite(Date.parse(bar.openTime))) {
    return false;
  }

  if (bar.high < bar.low) return false;
  if (bar.high < Math.max(bar.open, bar.close)) return false;
  if (bar.low > Math.min(bar.open, bar.close)) return false;

  return true;
}

/**
 * Fetches the most recent candles for one instrument and interval. Only closed
 * and structurally valid candles are returned, oldest first, without duplicate
 * open times.
 */
export async function fetchCandles(
  symbol: string,
  timeframe: PriceInterval,
  limit = PRICE_CANDLE_LIMIT,
): Promise<PriceCandle[]> {
  const url = new URL(
    `${BIQUOTE_BASE_URL}/${encodeURIComponent(symbol)}/ohlc`,
  );

  url.searchParams.set("interval", timeframe);
  url.searchParams.set("limit", String(limit));

  const response = await fetch(url, {
    signal: AbortSignal.timeout(20_000),
  });

  if (!response.ok) {
    throw new Error(`HTTP ${response.status}`);
  }

  const data = (await response.json()) as BiquoteOhlcResponse;

  if (!Array.isArray(data.bars)) {
    throw new Error("Invalid API response: bars is not an array");
  }

  const candles = new Map<number, PriceCandle>();

  for (const bar of data.bars) {
    if (bar.isOpen || !isValidBar(bar)) continue;

    const openTime = Date.parse(bar.openTime);

    if (candles.has(openTime)) continue;

    candles.set(openTime, {
      symbol,
      timeframe,
      openTime,
      open: bar.open,
      high: bar.high,
      low: bar.low,
      close: bar.close,
      volume: Number.isFinite(bar.volume) ? bar.volume : null,
      tickVolume: Number.isFinite(bar.tickVolume) ? bar.tickVolume : null,
    });
  }

  return [...candles.values()].sort((a, b) => a.openTime - b.openTime);
}
